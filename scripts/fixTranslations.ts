async function main() {
  const words: any[] = JSON.parse(fs.readFileSync(FILE, 'utf-8'))

  let restored = 0, fixed = 0

  for (const w of words) {
    // 1. Restore built-in dictionary
    if (DICT[w.word] && w.meaning !== DICT[w.word]) {
      w.meaning = DICT[w.word]
      restored++
    }
    // 2. Apply specific fixes
    if (FIXES[w.word] && w.type === 'verb') {
      w.meaning = FIXES[w.word]
      fixed++
    }
  }

  console.log(`Restored built-in: ${restored}`)
  console.log(`Fixed ambiguous: ${fixed}`)

  // Final check: any obvious errors remaining?
  const badPatterns = ['铅', '电梯', '姓名', '春天', '对象', '植物', '标志', '比尔', '罢工', '环']
  const stillBad: any[] = []
  for (const w of words) {
    if (w.type === 'verb' && badPatterns.some(b => w.meaning.includes(b))) {
      stillBad.push(w)
    }
  }
  if (stillBad.length > 0) {
    console.log(`\n⚠ Still bad: ${stillBad.length}`)
    stillBad.forEach((w: any) => console.log(`  ${w.word} → ${w.meaning} (EN: ${w.meaningEn})`))
  } else {
    console.log('\n✅ All known errors fixed.')
  }

  fs.writeFileSync(FILE, JSON.stringify(words, null, 2), 'utf-8')
  console.log('Saved.')

  // Show sample verbs
  console.log('\n📋 Verb samples:')
  words.filter((w: any) => w.type === 'verb').slice(0, 20).forEach((v: any) =>
    console.log(`  ${v.word} → ${v.meaning}`)
  )
}

main().catch(console.error)
